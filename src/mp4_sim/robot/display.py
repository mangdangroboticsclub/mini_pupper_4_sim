"""The screen on the front of the base, as a visual-only overlay.

Each SKU's ``assets/<sku>/display/`` holds the screen's meshes, already in the
base frame, and ``display.json`` (generated by ``tools/build_display.py``). They
are kept out of ``pupper.xml`` on purpose: the screen has no mass and no
contacts, so it changes nothing the physics sees, and ``pupper.xml`` is hashed
into SKU 2's contract. Add it to a spec that is going to be looked at::

    spec = sku2.get_spec(strip_visuals=False)    # already has it
    display.add_display(spec, "sku_1")           # any other spec with a "base" body
"""
from __future__ import annotations

import json
from pathlib import Path

import mujoco

from .sku import resolve_sku

__all__ = ["display_dir", "load", "add_display"]


def display_dir(sku=None) -> Path:
    return resolve_sku(sku).dir / "display"


def load(sku=None) -> dict:
    """``display.json`` for the SKU."""
    return json.loads((display_dir(sku) / "display.json").read_text())


def add_display(spec: mujoco.MjSpec, sku=None, prefix: str = "") -> None:
    """Attach the screen to ``<prefix>base``: meshes, their materials and one geom each.

    The geoms are what the MJCF's ``visual`` class makes: group 1, no contacts,
    zero density, so the model's masses, inertias and contacts are unchanged.
    """
    info = load(sku)
    folder = display_dir(sku)
    body = spec.body(prefix + info["body"])
    for part in info["parts"]:
        name = prefix + part["mesh"]
        spec.add_mesh(name=name, file=str(folder / part["file"]))
        spec.add_material(name=name, rgba=part["rgba"], specular=0.3, shininess=0.4)
        body.add_geom(name=name, type=mujoco.mjtGeom.mjGEOM_MESH, meshname=name, material=name,
                      contype=0, conaffinity=0, group=1, density=0)
