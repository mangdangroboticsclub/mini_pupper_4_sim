"""Which Mini Pupper 4 variant (SKU) is modelled.

Every SKU is one folder under ``mp4_sim/robot/assets/<name>/`` holding the same
set of generated files (``pupper.xml``, ``scene.xml``, ``servo_map.json``,
``parts/``), plus the URDF and meshes ``tools/build_model.py`` built them from.
Everything that is a property of the *robot* (geometry, masses, the servo ->
joint map, the stand pose) comes from that folder; everything that is a
property of the *servos* (``servo_profiles.json``, the fitted BAM models) is
shared.

The SKU is chosen in two layers:

* a **global default** — :func:`set_sku`, the ``MP4_SIM_SKU`` environment
  variable, or ``--sku`` on any of the command-line tools — so a whole script
  can be switched without touching its code, and
* a **per-object choice** — ``ServoMap(sku=...)`` and the like — so one
  process can hold both robots::

    from mp4_sim.robot import sku
    sku.set_sku("sku_1")                     # everything below builds SKU 1

    with sku.use_sku("sku_2"):               # temporarily SKU 2
        ...

Pure Python: no MuJoCo here, so the choice can be made before anything heavy
is imported.
"""

from __future__ import annotations

import os
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterator, Optional, Tuple

__all__ = ["Sku", "SKUS", "DEFAULT_SKU", "available_skus", "resolve_sku", "get_sku", "set_sku",
           "use_sku", "add_sku_argument", "apply_sku_argument"]

_MODEL_DIR = Path(__file__).resolve().parent / "assets"

#: The SKU used when nothing else is said.
DEFAULT_SKU = "sku_2"


@dataclass(frozen=True)
class Sku:
    """One robot variant and where its model lives."""

    #: canonical name, also the folder under ``mp4_sim/robot/assets``
    name: str
    #: one line for humans
    title: str
    #: the cleaned-up URDF ``tools/build_model.py`` reads, under ``urdf/``
    urdf: str
    #: known gaps between this model and the real robot
    notes: Tuple[str, ...] = ()

    @property
    def dir(self) -> Path:
        return _MODEL_DIR / self.name

    @property
    def robot_xml(self) -> Path:
        """The robot alone (12 joints + the blue "ghost" copy the teleop viewer uses)."""
        return self.dir / "pupper.xml"

    @property
    def scene_xml(self) -> Path:
        """Robot + textured floor + lights. What the teleop viewer opens."""
        return self.dir / "scene.xml"

    @property
    def servo_map_json(self) -> Path:
        """firmware servo angle -> model joint angle (generated by ``tools/build_model.py``)."""
        return self.dir / "servo_map.json"

    @property
    def parts_dir(self) -> Path:
        return self.dir / "parts"

    @property
    def urdf_dir(self) -> Path:
        return self.dir / "urdf"

    @property
    def urdf_path(self) -> Path:
        return self.urdf_dir / self.urdf

    @property
    def meshes_dir(self) -> Path:
        return self.dir / "meshes"


SKUS: Dict[str, Sku] = {
    s.name: s for s in (
        Sku("sku_1", "Mini Pupper 4, SKU 1", "sku_1_urdf_fixed.urdf"),
        Sku("sku_2", "Mini Pupper 4, SKU 2 (longer body)", "sku_2_urdf_fixed.urdf", notes=(
            ("pupper.xml carries SKU 1's mass budget (360 g total, 65.5 g per motor module); "
             "robot.sku2 applies the weighed 450 g split (sku2_masses.json) at load time"),
            ("the URDF is a repaired SolidWorks export and is to be replaced by the "
             "mechanical team's updated SKU 2 URDF"),
        )),
    )
}

_current: Optional[str] = None


def available_skus() -> Tuple[str, ...]:
    return tuple(SKUS)


def _canonical(name: str) -> str:
    key = str(name).strip().lower().replace("-", "_").replace(" ", "_")
    if key.isdigit():
        key = f"sku_{key}"
    elif key.startswith("sku") and key[3:].isdigit():
        key = f"sku_{key[3:]}"
    return key


def resolve_sku(sku: "str | Sku | None" = None) -> Sku:
    """``None`` -> the global default; a name (``"sku_2"``, ``"sku2"``, ``"2"``) -> its SKU."""
    if isinstance(sku, Sku):
        return sku
    if sku is None:
        return get_sku()
    key = _canonical(sku)
    if key not in SKUS:
        raise ValueError(f"unknown SKU {sku!r}; expected one of {list(SKUS)}")
    return SKUS[key]


def get_sku() -> Sku:
    """The global default SKU: :func:`set_sku`, else ``MP4_SIM_SKU``, else :data:`DEFAULT_SKU`."""
    global _current
    if _current is None:
        _current = resolve_sku(os.environ.get("MP4_SIM_SKU") or DEFAULT_SKU).name
    return SKUS[_current]


def set_sku(sku: "str | Sku") -> Sku:
    """Set the global default SKU for everything built from now on."""
    global _current
    chosen = resolve_sku(sku)
    _current = chosen.name
    return chosen


@contextmanager
def use_sku(sku: "str | Sku") -> Iterator[Sku]:
    """Temporarily change the global default SKU."""
    previous = get_sku()
    try:
        yield set_sku(sku)
    finally:
        set_sku(previous)


def add_sku_argument(parser) -> None:
    """``--sku`` for an ``argparse`` parser; pair with :func:`apply_sku_argument`."""
    parser.add_argument("--sku", default=None, type=lambda s: resolve_sku(s).name,
                        metavar="|".join(SKUS),
                        help=f"robot variant (default: $MP4_SIM_SKU or {DEFAULT_SKU})")


def apply_sku_argument(args) -> Sku:
    """Make ``args.sku`` (if given) the global default; returns the SKU in effect."""
    if getattr(args, "sku", None):
        return set_sku(args.sku)
    return get_sku()
