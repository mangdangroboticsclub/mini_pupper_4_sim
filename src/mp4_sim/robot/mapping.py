"""firmware servo angles  <->  MuJoCo joint angles.

The robot streams 12 servo angles in degrees, in the firmware's own terms: the
angle ``servo_write()`` takes, ``0`` = the stand pose, calibration removed.
:class:`ServoMap` converts those to the 12 joint angles of ``assets/<sku>/pupper.xml``
and back.

  hip    straight rotation, direction from ``servo_map.json`` ``hip_dir``
  thigh  firmware IK angle ``th1 = th1n + sign * servo``
  knee   the knee motor drives the shin through a rod, so the *servo* sets the
         shin's angle to the vertical (firmware ``th2 = 90 - shin``). The
         model's knee is a plain hinge between thigh and shin, so its angle is
         ``shin - thigh`` against the model's zero pose.

``servo_map.json`` is generated by ``tools/build_model.py`` from the CAD, so it
also carries the two numbers the firmware and the CAD disagree about
(:data:`~mp4_sim.robot.kinematics.L1`, ``L2``).

Pure NumPy: no MuJoCo here, so this module (and the whole maths path) can be
imported and tested without the simulator installed.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

from .kinematics import JOINT_ORDER, LEG_ORDER, SERVO_IDS
from .sku import resolve_sku

__all__ = ["ServoMap", "JOINT_ORDER", "LEG_ORDER"]


class ServoMap:
    """Bidirectional firmware-servo <-> model-joint conversion.

    Angles are always in the package's fixed order: 12 values, legs in
    :data:`LEG_ORDER` (FR, FL, RR, RL), each leg ``hip, thigh, calf``.

    ``path`` is a ``servo_map.json``; without one, the map of ``sku`` (default:
    the global SKU, see :mod:`mp4_sim.robot.sku`) is used.
    """

    def __init__(self, path: str | Path | None = None, *, sku=None):
        if path is None:
            path = resolve_sku(sku).servo_map_json
        with open(path) as fh:
            self.cfg = json.load(fh)
        fw = self.cfg["firmware"]
        self.path = Path(path)
        self.th1n_deg = float(fw["th1n_deg"])
        self.th2n_deg = float(fw["th2n_deg"])
        self.legs = self.cfg["legs"]

    # ---- properties -----------------------------------------------------
    @property
    def joint_names(self) -> tuple[str, ...]:
        return JOINT_ORDER

    def servo_ids(self, leg: str) -> tuple[int, int, int]:
        """``(hip, thigh, knee)`` 1-based servo ids for a leg."""
        return SERVO_IDS[leg]

    def stand_joint_angles(self) -> np.ndarray:
        """Joint angles (rad, 12) for servo angles of 0 — the stand pose."""
        return self.servo_to_joint(np.zeros(12))

    # ---- servo -> joint -------------------------------------------------
    def servo_to_joint(self, servo_deg) -> np.ndarray:
        """12 firmware servo angles (degrees) -> 12 model joint angles (rad)."""
        servo = np.asarray(servo_deg, dtype=float).reshape(12)
        q = np.zeros(12)
        for k, leg in enumerate(LEG_ORDER):
            leg_cfg = self.legs[leg]
            ids = leg_cfg["servos"]
            axis = leg_cfg["axis_sign"]
            zero = leg_cfg["zero_pose_deg"]
            a_hip = servo[ids["hip"] - 1]
            a_thigh = servo[ids["thigh"] - 1]
            a_knee = servo[ids["knee"] - 1]

            th1 = self.th1n_deg + leg_cfg["ik_sign"]["thigh"] * a_thigh   # thigh from vertical
            th2 = self.th2n_deg + leg_cfg["ik_sign"]["knee"] * a_knee
            a1 = th1                                                      # thigh from vertical
            a2 = 90.0 - th2                                               # shin from vertical

            q[3 * k + 0] = math.radians(axis["hip"] * leg_cfg["hip_dir"] * a_hip)
            q[3 * k + 1] = math.radians(-axis["thigh"] * (a1 - zero["thigh"]))
            q[3 * k + 2] = math.radians(
                -axis["knee"] * ((a2 - a1) - (zero["shin"] - zero["thigh"]))
            )
        return q

    # ---- joint -> servo -------------------------------------------------
    def joint_to_servo(self, joint_rad) -> np.ndarray:
        """12 model joint angles (rad) -> 12 firmware servo angles (degrees)."""
        q = np.asarray(joint_rad, dtype=float).reshape(12)
        servo = np.zeros(12)
        for k, leg in enumerate(LEG_ORDER):
            leg_cfg = self.legs[leg]
            ids = leg_cfg["servos"]
            axis = leg_cfg["axis_sign"]
            zero = leg_cfg["zero_pose_deg"]
            ik = leg_cfg["ik_sign"]

            q_hip, q_thigh, q_knee = (math.degrees(q[3 * k + i]) for i in range(3))

            a_hip = q_hip / (axis["hip"] * leg_cfg["hip_dir"])
            a1 = zero["thigh"] - q_thigh / axis["thigh"]
            a2 = a1 + (zero["shin"] - zero["thigh"]) - q_knee / axis["knee"]

            servo[ids["hip"] - 1] = a_hip
            servo[ids["thigh"] - 1] = (a1 - self.th1n_deg) / ik["thigh"]
            servo[ids["knee"] - 1] = ((90.0 - a2) - self.th2n_deg) / ik["knee"]
        return servo

    # ---- conveniences ---------------------------------------------------
    def servo_to_joint_dict(self, servo_deg) -> dict[str, float]:
        q = self.servo_to_joint(servo_deg)
        return dict(zip(JOINT_ORDER, q.tolist()))

    def affine(self):
        """``(A, b)`` such that ``q = A @ servo_deg + b``.

        The mapping is affine in the servo angles (see the derivation above), so
        a whole recording or trajectory converts with one matrix multiply. The
        matrix is built *from* :meth:`servo_to_joint`, so there is still only one
        implementation of the maths.
        """
        if getattr(self, "_affine", None) is None:
            identity = np.eye(12)
            b = self.servo_to_joint(np.zeros(12))
            a = np.column_stack([self.servo_to_joint(identity[:, j]) - b for j in range(12)])
            self._affine = (a, b)
        return self._affine

    def servo_to_joint_array(self, servo_deg) -> np.ndarray:
        """Vectorised :meth:`servo_to_joint` for ``(N, 12)`` input (degrees)."""
        servo = np.asarray(servo_deg, dtype=float)
        single = servo.ndim == 1
        servo = np.atleast_2d(servo)
        a, b = self.affine()
        q = servo @ a.T + b
        return q[0] if single else q

    def clamp_servo(self, servo_deg, lo: float = 0.0, hi: float = 1023.0):
        """Clamp to the firmware's own servo tick range (in degrees: the
        firmware's ``0..1023`` counts map onto ``0..300`` degrees)."""
        return np.clip(np.asarray(servo_deg, dtype=float), lo, hi)
